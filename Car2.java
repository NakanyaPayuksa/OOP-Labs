public class Car2 {
    // Multiple Constructors
    public int speed;
    public String color;
    private double weight;

    public Car2(String c) {
        color = c;
        speed = 0;
        weight = 1000.0d;
    }

public Car2 ( String c, int s) {
color = c;
speed = s;
weight = 1000.0d;
    }
}
